#!/usr/bin/env python3
"""Extract the 8 tops and 8 sleeve pairs from the supplied 8x2 sheet.

Requires Pillow for this development-time asset step. It removes only the
near-white background connected to a tile edge; enclosed white fabric stays.
"""
from collections import deque
import hashlib
from pathlib import Path
import base64
import io

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "wardrobe" / "source-sheet.png"
OUTPUT = ROOT / "assets" / "wardrobe" / "pieces"
MODULE = ROOT / "src" / "wardrobe-art.js"
SHEET_SHA256 = "B49BF9A38A54603CF1D0931C1DF8C1D9287A362B7D96EA8E56203FA333BA94B5"


def remove_edge_paper(tile: Image.Image) -> Image.Image:
    rgba = tile.convert("RGBA")
    pix = rgba.load()
    width, height = rgba.size
    seen = bytearray(width * height)
    queue = deque()

    def paper_color(x: int, y: int) -> bool:
        r, g, b, _ = pix[x, y]
        return min(r, g, b) >= 235 and max(r, g, b) - min(r, g, b) <= 22

    # Close one-pixel breaks in dark outlines before flood filling. This keeps
    # open folds from connecting the background flood to white garment fabric.
    barrier = Image.new("L", (width, height))
    barrier.putdata([0 if paper_color(x, y) else 255
                     for y in range(height) for x in range(width)])
    barrier = barrier.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3)).load()

    def paper(x: int, y: int) -> bool:
        return barrier[x, y] == 0 and paper_color(x, y)

    def add(x: int, y: int) -> None:
        offset = y * width + x
        if not seen[offset] and paper(x, y):
            seen[offset] = 1
            queue.append((x, y))

    for x in range(width):
        add(x, 0)
        add(x, height - 1)
    for y in range(height):
        add(0, y)
        add(width - 1, y)

    while queue:
        x, y = queue.popleft()
        pix[x, y] = (0, 0, 0, 0)
        if x:
            add(x - 1, y)
        if x + 1 < width:
            add(x + 1, y)
        if y:
            add(x, y - 1)
        if y + 1 < height:
            add(x, y + 1)

    return rgba


def trim(image: Image.Image) -> Image.Image:
    bounds = image.getchannel("A").getbbox()
    if not bounds:
        raise ValueError("A tile produced an empty transparent image")
    return image.crop(bounds)


def to_data_uri(path: Path) -> str:
    image = Image.open(path).convert("RGBA")
    out = io.BytesIO()
    image.save(out, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(out.getvalue()).decode("ascii")


def main() -> None:
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest().upper()
    if source_hash != SHEET_SHA256:
        raise ValueError(f"Unexpected wardrobe source hash: {source_hash}")
    sheet = Image.open(SOURCE).convert("RGB")
    if sheet.size != (2172, 724):
        raise ValueError(f"Unexpected source sheet dimensions: {sheet.size}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    tops: list[dict] = []
    sleeves: list[list[dict]] = []

    for column in range(8):
        # Keep the pale anti-aliased frame outside the crop; each card boundary
        # is 3-8 px wide and can otherwise disconnect the paper flood fill.
        left = round(column * sheet.width / 8) + 10
        right = round((column + 1) * sheet.width / 8) - 10
        top = trim(remove_edge_paper(sheet.crop((left, 10, right, 382))))
        top_path = OUTPUT / f"top-{column + 1:02}.png"
        top.save(top_path, optimize=True)
        tops.append({"width": top.width, "height": top.height, "image": to_data_uri(top_path)})

        # The lower row contains a left/right sleeve pair in each matching cell.
        lower_crop = sheet.crop((left, 405, right, 712))
        bottom = remove_edge_paper(lower_crop)
        middle = bottom.width // 2
        pair = []
        for side, bounds in (("left", (0, 0, middle, bottom.height)),
                             ("right", (middle, 0, bottom.width, bottom.height))):
            piece = trim(bottom.crop(bounds))
            path = OUTPUT / f"sleeve-{side}-{column + 1:02}.png"
            piece.save(path, optimize=True)
            pair.append({"width": piece.width, "height": piece.height, "image": to_data_uri(path)})
        sleeves.append(pair)

    lines = [
        "// Generated by scripts/extract-wardrobe-assets.py from the user's sheet.",
        f"// Source SHA-256: {SHEET_SHA256}",
        '(function(root){"use strict";var art={tops:[',
    ]
    lines.append(",\n".join("{width:%d,height:%d,image:%r}" % (item["width"], item["height"], item["image"]) for item in tops))
    lines.append("],sleeves:[")
    lines.append(",\n".join("[" + ",".join("{width:%d,height:%d,image:%r}" % (item["width"], item["height"], item["image"]) for item in pair) + "]" for pair in sleeves))
    lines.append("]};root.GachaWardrobeArt=art;if(typeof module!==\"undefined\"&&module.exports)module.exports=art;})(typeof window!==\"undefined\"?window:globalThis);\n")
    MODULE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Extracted {len(tops)} tops and {len(sleeves)} sleeve pairs from {sheet.size} sheet.")


if __name__ == "__main__":
    main()
