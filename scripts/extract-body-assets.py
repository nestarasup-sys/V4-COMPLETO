"""Create transparent, articulated sprites from the author's original PNG.

Requires Pillow (`python -m pip install Pillow`) only when regenerating assets.
The original source is copied byte-for-byte to assets/body-original.png. The
generated PNG sprites keep the original artwork pixels and add transparent
green-key removal; no contour is redrawn.
"""
from __future__ import annotations

import base64
import argparse
import io
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ORIGINAL = ROOT / "assets" / "body-original.png"
PARTS = ROOT / "assets" / "body-parts"
MODULE = ROOT / "src" / "body-art.js"
EXPECTED_SIZE = (1122, 1402)

# Crop rectangles follow the actual ten separated shapes in the source sheet.
# Each crop retains its source-space origin so the rig can rotate it in place.
REGIONS = {
    "head": (400, 30, 716, 321),
    "armLU": (238, 307, 356, 499),
    "armRU": (766, 307, 883, 498),
    "torso": (464, 338, 678, 668),
    "armLL": (131, 505, 276, 761),
    "armRL": (845, 504, 990, 761),
    "legLU": (383, 673, 541, 946),
    "legRU": (602, 676, 768, 946),
    "legLL": (346, 962, 500, 1374),
    "legRL": (646, 961, 843, 1373),
}


def clamp(value: float, low: float, high: float) -> float:
    return min(high, max(low, value))


def png_data(image: Image.Image) -> str:
    output = io.BytesIO()
    image.save(output, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(output.getvalue()).decode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Original PNG; defaults to the preserved asset or the author's Downloads copy")
    source_path = parser.parse_args().source
    if source_path is None:
        external = Path(r"C:\Users\luiz\Downloads\Design sem nome (54).png")
        source_path = ORIGINAL if ORIGINAL.is_file() else external
    if not source_path.is_file():
        raise FileNotFoundError(f"Original PNG was not found: {source_path}")
    ORIGINAL.parent.mkdir(parents=True, exist_ok=True)
    PARTS.mkdir(parents=True, exist_ok=True)
    if source_path.resolve() != ORIGINAL.resolve():
        shutil.copyfile(source_path, ORIGINAL)

    source = Image.open(source_path).convert("RGB")
    if source.size != EXPECTED_SIZE:
        raise ValueError(f"Expected {EXPECTED_SIZE}, found {source.size}")
    pixels = source.load()
    module = ["// Generated by scripts/extract-body-assets.py; source pixels are in assets/body-original.png.",
              "(function(root){\"use strict\";var art={"]

    for index, (part, box) in enumerate(REGIONS.items()):
        left, top, right, bottom = box
        rgba = Image.new("RGBA", (right-left, bottom-top))
        shade = Image.new("RGBA", rgba.size)
        art_px, shade_px = rgba.load(), shade.load()
        for y in range(top, bottom):
            for x in range(left, right):
                r, g, b = pixels[x, y]
                excess = g - max(r, b)
                # In the foreground, cream fill has about -15 excess while
                # the original brown contour has about -64. Solve alpha
                # against the matching foreground range to avoid green halos.
                foreground_excess = -15 if r >= 160 else -64
                alpha = clamp((92 - excess) / (92 - foreground_excess), 0, 1)
                if alpha < 0.012:
                    continue
                out = [clamp((channel - key*(1-alpha))/alpha, 0, 255)
                       for channel, key in zip((r, g, b), (0, 191, 99))]
                a = round(alpha*255)
                art_px[x-left, y-top] = (*map(round, out), a)
                luminance = 0.2126*out[0] + 0.7152*out[1] + 0.0722*out[2]
                # Keep tint out of the dark outline and anti-aliased outline pixels.
                if luminance >= 164 and out[0] > out[2] + 3:
                    gray = round(clamp(luminance, 0, 255))
                    shade_px[x-left, y-top] = (gray, gray, gray, a)

        art_path = PARTS / f"{part}.png"
        shade_path = PARTS / f"{part}-skin-mask.png"
        rgba.save(art_path, optimize=True)
        shade.save(shade_path, optimize=True)
        module.append(f'  "{part}":{{x:{left},y:{top},width:{right-left},height:{bottom-top},image:"{png_data(rgba)}",shade:"{png_data(shade)}"}}' + ("," if index < len(REGIONS)-1 else ""))
        print(f"{part}: {right-left}x{bottom-top} at {left},{top}; art={art_path.stat().st_size} bytes")

    module.extend(["};root.GachaBodyArt=art;if(typeof module!==\"undefined\"&&module.exports)module.exports=art;})(typeof window!==\"undefined\"?window:globalThis);", ""])
    MODULE.write_text("\n".join(module), encoding="utf-8")
    print(f"Original source preserved byte-for-byte: {ORIGINAL} ({ORIGINAL.stat().st_size} bytes)")
    print(f"Browser sprite map generated: {MODULE} ({MODULE.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
